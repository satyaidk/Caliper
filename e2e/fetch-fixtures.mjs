import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Downloads one real file per supported extension, so every loader is exercised
 * against something a person would actually open rather than a synthetic cube.
 *
 * Sources are pinned to tagged versions. If one starts 404ing, the fixture is
 * missing rather than silently stale — the sweep will say so.
 */

const OUT = fileURLToPath(new URL('fixtures', import.meta.url));
fs.mkdirSync(OUT, { recursive: true });

const THREE = 'https://cdn.jsdelivr.net/gh/mrdoob/three.js@r169/examples/models';
const OCCT = 'https://cdn.jsdelivr.net/gh/kovacsv/occt-import-js@0.0.23/test/testfiles';

const WANT = [
  // --- mesh, already triangulated ---------------------------------------
  ['obj', `${THREE}/obj/walt/WaltHead.obj`],
  ['mtl', `${THREE}/obj/walt/WaltHead.mtl`],
  ['ply', `${THREE}/ply/ascii/dolphins.ply`],
  ['glb', `${THREE}/gltf/Nefertiti/Nefertiti.glb`],
  ['dae', `${THREE}/collada/elf/elf.dae`],
  ['3ds', `${THREE}/3ds/portalgun/portalgun.3ds`],
  ['3mf', `${THREE}/3mf/cube_gears.3mf`],
  ['amf', `${THREE}/amf/rook.amf`],
  ['wrl', `${THREE}/vrml/house.wrl`],
  ['fbx', `${THREE}/fbx/Samba%20Dancing.fbx`],
  ['3dm', `${THREE}/3dm/Rhino_Logo.3dm`],

  // --- CAD B-rep, tessellated on open ------------------------------------
  ['stp', `${OCCT}/cax-if/as1-oc-214.stp`],
  ['step', `${OCCT}/cax-if/as1_pe_203.stp`],
  ['brep', `${OCCT}/cax-if-brep/as1_pe_203.brep`],
  ['igs', `${OCCT}/cube-10x10mm/Cube%2010x10.igs`],
  ['fcstd', `${OCCT}/cube-fcstd/cube.FCStd`],
];

// stl, off, gltf and bim are generated by make-fixtures-extra.mjs — either no
// public sample is small enough to be worth pulling, or the obvious source 403s.

const results = [];

for (const [ext, url] of WANT) {
  const dest = path.join(OUT, `sample.${ext}`);
  try {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) {
      results.push([ext, `HTTP ${res.status}`, url]);
      continue;
    }
    const buf = Buffer.from(await res.arrayBuffer());
    fs.writeFileSync(dest, buf);
    results.push([ext, `${(buf.length / 1024).toFixed(0)} kB`, '']);
  } catch (e) {
    results.push([ext, 'ERR', e.message.slice(0, 70)]);
  }
}

let bad = 0;
for (const [ext, size, note] of results) {
  if (note) bad++;
  console.log(`  ${ext.padEnd(6)} ${String(size).padStart(9)}  ${note}`);
}
console.log(`\n  ${results.length - bad}/${results.length} downloaded into ${OUT}`);
process.exit(bad ? 1 : 0);
