/**
 * Reads a G-code file back into toolpaths for the Preview, so a print file
 * from Bambu Studio, OrcaSlicer, PrusaSlicer or Cura can be inspected layer by
 * layer next to Caliper's own slices.
 *
 * It follows the moves the way a printer would: absolute or relative XYZ
 * (`G90`/`G91`) and extrusion (`M82`/`M83`), `G92` resets, straight moves
 * (`G0`/`G1`) and arcs (`G2`/`G3` with I/J, which Bambu Studio writes for
 * most curves). Only moves that extrude are drawn. Feature names come from the
 * slicer's own comments (`; FEATURE:` in Bambu/Orca, `;TYPE:` in Prusa and
 * Cura) and layers from its layer markers, falling back to Z changes.
 *
 * When the file marks Bambu's machine start and end sequences, moves inside
 * them (the purge line, the nozzle wipe) are left out: they are not the part.
 */

export interface ParsedGcode {
  /** Segment endpoints, (x, y, z) per vertex, in millimetres. */
  positions: Float32Array;
  /** Feature index for each segment. */
  segmentFeatures: Uint16Array;
  /** Vertex count at the end of each layer (cumulative). */
  layerEnds: Uint32Array;
  layerZ: Float32Array;
  /** Feature names in first-seen order; `segmentFeatures` indexes into this. */
  features: string[];
  bounds: { min: [number, number, number]; max: [number, number, number] };
  header: GcodeHeader;
}

export interface GcodeHeader {
  generator: string | null;
  printSeconds: number | null;
  totalSeconds: number | null;
  filamentGrams: number | null;
  filamentMm: number | null;
}

export class GcodeParseError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'GcodeParseError';
  }
}

/** Slicer feature names mapped to the names Caliper's legend uses. */
const FEATURE_ALIASES: Record<string, string> = {
  // PrusaSlicer
  'external perimeter': 'Outer wall',
  perimeter: 'Inner wall',
  'overhang perimeter': 'Overhang wall',
  'internal infill': 'Sparse infill',
  'solid infill': 'Internal solid infill',
  'top solid infill': 'Top surface',
  'bridge infill': 'Bridge',
  'gap fill': 'Gap infill',
  'skirt/brim': 'Skirt',
  'support material': 'Support',
  'support material interface': 'Support interface',
  // Cura
  'wall-outer': 'Outer wall',
  'wall-inner': 'Inner wall',
  skin: 'Internal solid infill',
  fill: 'Sparse infill',
  support: 'Support',
  'support-interface': 'Support interface',
  skirt: 'Skirt',
};

function canonicalFeature(raw: string): string {
  const name = raw.trim();
  const alias = FEATURE_ALIASES[name.toLowerCase()];
  if (alias) return alias;
  return name ? name[0].toUpperCase() + name.slice(1) : 'Other';
}

/** Parses "1h 2m 3s", "17m 49s", "2d 3h" or plain seconds. */
export function parseDuration(text: string): number | null {
  const parts = [...text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)];
  if (!parts.length) return /^\s*\d+(\.\d+)?\s*$/.test(text) ? Number(text) : null;
  const unit = { d: 86400, h: 3600, m: 60, s: 1 } as const;
  return parts.reduce((sum, [, value, u]) => sum + Number(value) * unit[u as keyof typeof unit], 0);
}

function readHeader(text: string): GcodeHeader {
  // Headers live at the start (Bambu, Cura) or the end (Prusa, Orca) of a file.
  const head = text.slice(0, 20_000);
  const tail = text.slice(-20_000);
  const find = (pattern: RegExp) => pattern.exec(head) ?? pattern.exec(tail);
  const number = (pattern: RegExp) => {
    const match = find(pattern);
    return match ? Number(match[1]) : null;
  };
  const generator =
    /^; HEADER_BLOCK_START\s*\n;\s*(.+)$/m.exec(head)?.[1]?.trim() ??
    /^;\s*generated by (.+)$/im.exec(head)?.[1]?.trim() ??
    /^;\s*Generated with (.+)$/im.exec(head)?.[1]?.trim() ??
    null;
  const model = find(/; model printing time:\s*([^;\n]+)/i);
  const total = find(/total estimated time:\s*([^;\n]+)/i) ?? find(/estimated printing time \(normal mode\)\s*=\s*([^\n]+)/i);
  const cura = number(/^;TIME:(\d+)/m);
  return {
    generator,
    printSeconds: model ? parseDuration(model[1]) : cura,
    totalSeconds: total ? parseDuration(total[1]) : cura,
    filamentGrams: number(/total filament weight \[g\]\s*:\s*([\d.]+)/i) ?? number(/filament used \[g\]\s*=\s*([\d.]+)/i),
    filamentMm: number(/total filament length \[mm\]\s*:\s*([\d.]+)/i) ?? number(/filament used \[mm\]\s*=\s*([\d.]+)/i),
  };
}

const ARC_SEGMENT_MM = 0.5;
const MAX_VERTICES = 40_000_000;

export function parseGcode(text: string): ParsedGcode {
  const startEnd = text.indexOf('; MACHINE_START_GCODE_END');
  const endStart = text.indexOf('; MACHINE_END_GCODE_START');
  const from = startEnd >= 0 ? text.indexOf('\n', startEnd) + 1 : 0;
  const to = endStart > from ? endStart : text.length;

  const positions: number[] = [];
  const segmentFeatures: number[] = [];
  const layerEnds: number[] = [];
  const layerZ: number[] = [];
  const features: string[] = [];
  const featureIndex = new Map<string, number>();
  const min: [number, number, number] = [Infinity, Infinity, Infinity];
  const max: [number, number, number] = [-Infinity, -Infinity, -Infinity];

  let x = 0;
  let y = 0;
  let z = 0;
  let e = 0;
  let absoluteXYZ = true;
  let absoluteE = true;
  let feature = -1;
  let markedLayers = false;
  let layerOpen = false;
  let pendingLayerZ: number | null = null;
  let lastLayerZ = -Infinity;

  const useFeature = (name: string) => {
    const canonical = canonicalFeature(name);
    let index = featureIndex.get(canonical);
    if (index === undefined) {
      index = features.length;
      features.push(canonical);
      featureIndex.set(canonical, index);
    }
    feature = index;
  };

  const closeLayer = () => {
    if (layerOpen) layerEnds.push(positions.length / 3);
    layerOpen = false;
  };
  const openLayer = (atZ: number) => {
    closeLayer();
    layerZ.push(atZ);
    lastLayerZ = atZ;
    layerOpen = true;
  };
  const addSegment = (x0: number, y0: number, z0: number, x1: number, y1: number, z1: number) => {
    if (feature < 0) useFeature('Other');
    if (!layerOpen) openLayer(pendingLayerZ ?? z1);
    else if (!markedLayers && z1 > lastLayerZ + 1e-4) openLayer(z1);
    if (positions.length / 3 >= MAX_VERTICES) throw new GcodeParseError('This G-code is too large to preview in the browser.');
    positions.push(x0, y0, z0, x1, y1, z1);
    segmentFeatures.push(feature);
    for (const [px, py, pz] of [[x0, y0, z0], [x1, y1, z1]]) {
      if (px < min[0]) min[0] = px;
      if (py < min[1]) min[1] = py;
      if (pz < min[2]) min[2] = pz;
      if (px > max[0]) max[0] = px;
      if (py > max[1]) max[1] = py;
      if (pz > max[2]) max[2] = pz;
    }
  };

  let index = from;
  while (index < to) {
    let next = text.indexOf('\n', index);
    if (next < 0 || next > to) next = to;
    const line = text.slice(index, next).trim();
    index = next + 1;
    if (!line) continue;

    if (line[0] === ';') {
      const featureMatch = /^;\s*(?:FEATURE|TYPE)\s*:\s*(.+)$/.exec(line);
      if (featureMatch) {
        useFeature(featureMatch[1]);
        continue;
      }
      if (/^;\s*(CHANGE_LAYER|LAYER_CHANGE)\b/.test(line) || /^;LAYER:-?\d+/.test(line)) {
        markedLayers = true;
        closeLayer();
        pendingLayerZ = null;
        continue;
      }
      const height = /^;\s*Z_HEIGHT\s*:\s*([\d.]+)/.exec(line) ?? /^;Z:([\d.]+)/.exec(line);
      if (height) pendingLayerZ = Number(height[1]);
      continue;
    }

    const code = line.replace(/;.*$/, '').trim();
    const space = code.indexOf(' ');
    const command = (space < 0 ? code : code.slice(0, space)).toUpperCase();
    if (command === 'G90') absoluteXYZ = true;
    else if (command === 'G91') absoluteXYZ = false;
    else if (command === 'M82') absoluteE = true;
    else if (command === 'M83') absoluteE = false;
    if (command !== 'G0' && command !== 'G1' && command !== 'G2' && command !== 'G3' && command !== 'G92') continue;

    const params: Record<string, number> = {};
    for (const token of code.slice(command.length).trim().split(/\s+/)) {
      const match = /^([A-Za-z])(-?\d*\.?\d+)$/.exec(token);
      if (match) params[match[1].toUpperCase()] = Number(match[2]);
    }
    if (command === 'G92') {
      if (params.E !== undefined) e = params.E;
      if (params.X !== undefined) x = params.X;
      if (params.Y !== undefined) y = params.Y;
      if (params.Z !== undefined) z = params.Z;
      continue;
    }

    const target = (axis: 'X' | 'Y' | 'Z', current: number) =>
      params[axis] === undefined ? current : absoluteXYZ ? params[axis] : current + params[axis];
    const nx = target('X', x);
    const ny = target('Y', y);
    const nz = target('Z', z);
    let extruding = false;
    if (params.E !== undefined) {
      const delta = absoluteE ? params.E - e : params.E;
      e = absoluteE ? params.E : e + params.E;
      extruding = delta > 1e-7;
    }

    if (extruding && (command === 'G2' || command === 'G3') && (params.I !== undefined || params.J !== undefined)) {
      const cx = x + (params.I ?? 0);
      const cy = y + (params.J ?? 0);
      const radius = Math.hypot(x - cx, y - cy);
      const start = Math.atan2(y - cy, x - cx);
      let end = Math.atan2(ny - cy, nx - cx);
      const clockwise = command === 'G2';
      if (clockwise && end >= start - 1e-9) end -= Math.PI * 2;
      if (!clockwise && end <= start + 1e-9) end += Math.PI * 2;
      const sweep = end - start;
      const steps = Math.max(2, Math.min(720, Math.ceil((Math.abs(sweep) * radius) / ARC_SEGMENT_MM)));
      let px = x;
      let py = y;
      let pz = z;
      for (let step = 1; step <= steps; step++) {
        const t = step / steps;
        const angle = start + sweep * t;
        const qx = step === steps ? nx : cx + radius * Math.cos(angle);
        const qy = step === steps ? ny : cy + radius * Math.sin(angle);
        const qz = z + (nz - z) * t;
        addSegment(px, py, pz, qx, qy, qz);
        px = qx;
        py = qy;
        pz = qz;
      }
    } else if (extruding && (nx !== x || ny !== y)) {
      addSegment(x, y, z, nx, ny, nz);
    }
    x = nx;
    y = ny;
    z = nz;
  }
  closeLayer();

  // Drop layers that ended up empty (markers with no extrusion after them).
  const keptEnds: number[] = [];
  const keptZ: number[] = [];
  let previous = 0;
  layerEnds.forEach((end, i) => {
    if (end > previous) {
      keptEnds.push(end);
      keptZ.push(layerZ[i]);
    }
    previous = end;
  });
  if (!positions.length) throw new GcodeParseError('The file has no extrusion moves to preview.');

  return {
    positions: new Float32Array(positions),
    segmentFeatures: new Uint16Array(segmentFeatures),
    layerEnds: new Uint32Array(keptEnds),
    layerZ: new Float32Array(keptZ),
    features,
    bounds: { min, max },
    header: readHeader(text),
  };
}
